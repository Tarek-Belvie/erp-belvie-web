-- ================================================================================================
-- 002 — Comptes utilisateurs et sessions (nouveau avec la version web).
-- Les mots de passe sont stockés hachés (bcrypt) ; les sessions par empreinte SHA-256 du jeton,
-- jamais le jeton lui-même : une fuite de la table ne permet pas d'ouvrir une session.
-- ================================================================================================
CREATE TABLE utilisateurs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  nom TEXT NOT NULL,
  mot_de_passe_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'utilisateur' CHECK (role IN ('admin', 'utilisateur')),
  actif BIGINT NOT NULL DEFAULT 1 CHECK (actif IN (0, 1)),
  derniere_connexion TEXT,
  created_at TEXT NOT NULL DEFAULT (maintenant()),
  updated_at TEXT NOT NULL DEFAULT (maintenant())
);
CREATE UNIQUE INDEX idx_utilisateurs_email ON utilisateurs (lower(email));
CREATE TRIGGER trg_utilisateurs_updated_at BEFORE UPDATE ON utilisateurs FOR EACH ROW EXECUTE FUNCTION maj_updated_at();

CREATE TABLE sessions (
  empreinte TEXT PRIMARY KEY,
  utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id) ON DELETE CASCADE,
  expire_le TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  derniere_activite TIMESTAMPTZ NOT NULL DEFAULT now(),
  adresse_ip TEXT,
  navigateur TEXT
);
CREATE INDEX idx_sessions_utilisateur ON sessions (utilisateur_id);
