CREATE TABLE achats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid TEXT NOT NULL UNIQUE,
  fournisseur_id BIGINT NOT NULL REFERENCES fournisseurs(id),
  commande_id BIGINT REFERENCES commandes(id),
  categorie TEXT NOT NULL CHECK (categorie IN (
    'matiere', 'fourniture', 'confection', 'impression', 'transport', 'retouche', 'emballage', 'autre'
  )),
  designation TEXT NOT NULL,
  matiere_catalogue_id BIGINT REFERENCES matieres_catalogue(id),  -- identifie le composant pour le
                                                 -- suivi de stock (matière ET fourniture) ; NULL pour
                                                 -- les achats non catalogués ou les prestations
