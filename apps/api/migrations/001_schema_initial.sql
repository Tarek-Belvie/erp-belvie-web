-- ================================================================================================
-- 001 — Schéma initial PostgreSQL, converti du schéma SQLite final de Belvie ERP 1.0.1.
-- Généré par tools/schema/sqlite-vers-postgres.js puis relu. Ce fichier fait foi.
--
-- Choix de conversion (phase 1 : iso-fonctionnel) :
--   * INTEGER → BIGINT ; clés primaires → IDENTITY (BY DEFAULT, pour la reprise des données) ;
--   * REAL → DOUBLE PRECISION ;
--   * dates conservées en TEXT au format SQLite ('AAAA-MM-JJ' / 'AAAA-MM-JJ HH:MM:SS', UTC) ;
--   * datetime('now') / date('now') → maintenant() / aujourdhui() (définies ci-dessous) ;
--   * triggers updated_at réécrits en PL/pgSQL.
-- ================================================================================================

CREATE OR REPLACE FUNCTION maintenant() RETURNS TEXT LANGUAGE sql STABLE AS
  $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;
CREATE OR REPLACE FUNCTION aujourdhui() RETURNS TEXT LANGUAGE sql STABLE AS
  $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD') $$;

CREATE TABLE accessoires_catalogue (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom TEXT NOT NULL,
  nom_normalise TEXT NOT NULL UNIQUE,
  -- Famille par défaut proposée quand cette désignation est choisie dans l'autocomplétion.
  -- Sert de PRÉREMPLISSAGE, jamais de liste figée : chaque ligne reste modifiable, désactivable,
  -- et l'utilisateur peut en créer d'autres à la volée (même principe que postes_cout_predefinis).
  famille TEXT NOT NULL DEFAULT 'composant' CHECK (famille IN ('habillage', 'composant')),
  ordre BIGINT DEFAULT 0,
  actif BIGINT DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (maintenant())
);

CREATE TABLE fournisseurs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom TEXT NOT NULL,
  activite TEXT,                     -- ex: "Tissu / Matière" — descriptif libre, affiché dans la liste
  contact TEXT,
  telephone TEXT,
  email TEXT,
  adresse TEXT,
  conditions_paiement_defaut TEXT,   -- ancien champ texte libre, conservé mais plus jamais rempli
                                      -- ni affiché depuis la structuration ci-dessous
  delai_paiement_jours BIGINT,      -- 0 = comptant ; NULL = non renseigné
  delai_fin_de_mois BIGINT NOT NULL DEFAULT 0,  -- le délai démarre en fin de mois de facturation
                                      -- (ex: "30 jours fin de mois" = delai_paiement_jours=30 + ce flag)
  mode_paiement_defaut TEXT,         -- virement / cheque / especes / traite / autre
  notes TEXT,
  actif BIGINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (maintenant()),
  updated_at TEXT NOT NULL DEFAULT (maintenant())
);

CREATE TABLE listes_valeurs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK (type IN ('produit','couleur','responsable','atelier','taille','saison','rayon','operateur','coupe','pointure','categorie')),
  nom TEXT NOT NULL,
  nom_normalise TEXT NOT NULL,       -- nom en minuscules/espaces nettoyés, pour détecter les doublons
  code TEXT,                         -- toujours en MAJUSCULES ; NULL sauf pour saison/rayon
  ordre BIGINT,                     -- NULL = non pertinent pour ce type (tri alphabétique)
  responsable_nom TEXT,              -- texte libre, utilisé uniquement pour type='atelier' : le
                                      -- responsable par défaut de cet atelier, sans liste dédiée
  fournisseur_id BIGINT REFERENCES fournisseurs(id),  -- utilisé uniquement pour type='atelier',
                                      -- optionnel : renseigné seulement si cet atelier doit être
                                      -- payé (module Finance) — la notion opérationnelle d'atelier
                                      -- reste inchangée, aucun impact sur le reste de la production
  actif BIGINT NOT NULL DEFAULT 1,  -- 0 = n'apparaît plus dans les nouvelles commandes, historique conservé
  created_at TEXT NOT NULL DEFAULT (maintenant()), parent_id BIGINT REFERENCES listes_valeurs(id),
  UNIQUE(type, nom_normalise)
);

CREATE TABLE articles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid TEXT NOT NULL UNIQUE,
  produit_id BIGINT REFERENCES listes_valeurs(id),  -- nullable : un article peut exister sans
                                                          -- type de produit assigné (ex: converti
                                                          -- depuis Planification sans cette info),
                                                          -- à compléter plus tard si besoin
  saison_id BIGINT REFERENCES listes_valeurs(id),
  annee_collection BIGINT,                    -- entier 4 chiffres, ex: 2026
  rayon_id BIGINT REFERENCES listes_valeurs(id),
  categorie_id BIGINT REFERENCES listes_valeurs(id),  -- ajoutée progressivement ; référentiel déjà
                                                          -- existant (Paramètres → Catalogue produit),
                                                          -- jamais utilisé sur l'article jusqu'ici
  prix_vente_envisage DOUBLE PRECISION,                    -- simulation Finance : marge/taux/prix plancher se
                                                -- calculent à partir de ce prix et du coût (prévi/réel),
                                                -- jamais stockés eux-mêmes
  -- Nom commercial de CET article : « T-shirt oversize », « Pull Zip up uni ».
  -- Indispensable depuis que produit_id désigne un TYPE générique (T-shirt, Pull) : sans elle,
  -- deux articles du même type seraient indiscernables partout où p.nom était affiché
  -- (commandes.js, ficheTechnique.js, bcPf.js). Toutes les lectures font COALESCE(designation, p.nom).
  designation TEXT,
  abreviation TEXT,                            -- 2 à 5 lettres majuscules, ex: JEA
  numero_sequentiel BIGINT,                   -- calculé automatiquement à la génération
  reference_principale TEXT UNIQUE,            -- ex: FW26-M-JEA-01 ; générée une fois, jamais réécrite
  est_demo BIGINT NOT NULL DEFAULT 0,         -- 1 = article de démonstration, supprimable avec les commandes de démo
  created_at TEXT NOT NULL DEFAULT (maintenant()),
  updated_at TEXT NOT NULL DEFAULT (maintenant()),
  CHECK (abreviation IS NULL OR (abreviation = UPPER(abreviation) AND LENGTH(abreviation) BETWEEN 2 AND 5))
);

CREATE TABLE etapes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cle TEXT NOT NULL UNIQUE,          -- identifiant stable, ex: "coupe" (ne pas afficher)
  libelle TEXT NOT NULL,             -- texte affiché, modifiable librement
  pourcentage BIGINT NOT NULL DEFAULT 0,  -- avancement associé (non utilisé actuellement, réservé)
  ordre BIGINT NOT NULL,            -- position dans le flux de production
  optionnelle BIGINT NOT NULL DEFAULT 0,  -- 1 = peut être ignorée (ex: broderie/impression)
  actif BIGINT NOT NULL DEFAULT 1   -- 0 = masquée des nouvelles commandes, conservée pour l'historique
);

CREATE TABLE commandes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,       -- identifiant technique interne (usage futur inter-modules)
  uuid TEXT NOT NULL UNIQUE,                  -- identifiant global stable (sauvegardes, exports, futur réseau)
  numero TEXT UNIQUE,                         -- numéro OFFICIEL, attribué à la validation seulement (NULL en brouillon)
  article_id BIGINT NOT NULL REFERENCES articles(id),
  type_production TEXT NOT NULL DEFAULT 'nouveau' CHECK (type_production IN ('nouveau','reassort')),
  numero_reassort BIGINT,                    -- NULL sauf si type_production = 'reassort'
  reference_production TEXT,                  -- référence article, ou article-R01/-R02... pour un réassort
  responsable_nom TEXT NOT NULL,               -- texte libre — pas de liste dédiée des responsables ;
                                                -- suggéré depuis le responsable de l'atelier choisi,
                                                -- mais librement modifiable par commande
  atelier_id BIGINT NOT NULL REFERENCES listes_valeurs(id),
  quantite_totale BIGINT NOT NULL DEFAULT 0, -- somme des lignes (commande_lignes) ; jamais saisie directement
  date_lancement TEXT NOT NULL,               -- ISO 8601 (YYYY-MM-DD)
  date_fin_prevue TEXT NOT NULL,
  etape_id BIGINT NOT NULL REFERENCES etapes(id),
  statut TEXT NOT NULL DEFAULT 'brouillon'
    CHECK (statut IN ('brouillon','validee','en_production','controle_qualite','terminee','annulee')),
  priorite TEXT NOT NULL DEFAULT 'normale'
    CHECK (priorite IN ('haute','normale','faible')),
  -- Bloquée est un indicateur séparé du statut (une commande En production peut être bloquée).
  bloquee BIGINT NOT NULL DEFAULT 0,
  blocage_motif TEXT,
  bloquee_le TEXT, bloquee_par_id BIGINT REFERENCES listes_valeurs(id),
  debloquee_le TEXT, debloquee_par_id BIGINT REFERENCES listes_valeurs(id),
  -- Horodatage + opérateur de chaque transition officielle (doublé par historique_transitions,
  -- qui conserve tout l'historique ; ces colonnes ne gardent que le DERNIER événement de chaque type).
  valide_le TEXT, valide_par_id BIGINT REFERENCES listes_valeurs(id),
  lance_le TEXT, lance_par_id BIGINT REFERENCES listes_valeurs(id),
  controle_qualite_le TEXT, controle_qualite_par_id BIGINT REFERENCES listes_valeurs(id),
  terminee_le TEXT, terminee_par_id BIGINT REFERENCES listes_valeurs(id),
  annulee_le TEXT, annulee_par_id BIGINT REFERENCES listes_valeurs(id), annulation_motif TEXT,
  archived_le TEXT, archived_par_id BIGINT REFERENCES listes_valeurs(id),
  desarchive_le TEXT, desarchive_par_id BIGINT REFERENCES listes_valeurs(id),
  commentaires TEXT,
  archived BIGINT NOT NULL DEFAULT 0,        -- 1 = archivée (conservée, hors vues actives)
  est_demo BIGINT NOT NULL DEFAULT 0,        -- 1 = donnée de démonstration, supprimable en un clic
  deleted_at TEXT,                            -- suppression douce, réservée aux brouillons (voir commandes.js)
  created_at TEXT NOT NULL DEFAULT (maintenant()),
  updated_at TEXT NOT NULL DEFAULT (maintenant()),
  -- La TEXT limite de production ne peut pas précéder la TEXT de lancement.
  CHECK (date_fin_prevue >= date_lancement),
  -- Le motif du blocage est obligatoire uniquement lorsque l'indicateur "bloquée" est actif.
  CHECK (bloquee = 0 OR (blocage_motif IS NOT NULL AND TRIM(blocage_motif) <> ''))
);

