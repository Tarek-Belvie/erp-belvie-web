-- Gradations : les deux tailles doivent appartenir à la même fiche (anciens triggers SQLite
-- trg_ft_gradations_meme_fiche_insert / _update, réunis en un seul).
CREATE OR REPLACE FUNCTION verifier_gradation_meme_fiche() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (SELECT fiche_id FROM ft_tailles WHERE id = NEW.taille_depart_id) <> NEW.fiche_id
     OR (SELECT fiche_id FROM ft_tailles WHERE id = NEW.taille_arrivee_id) <> NEW.fiche_id THEN
    RAISE EXCEPTION 'Gradation : les deux tailles doivent appartenir a cette fiche technique.';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_ft_gradations_meme_fiche BEFORE INSERT OR UPDATE ON ft_mesures_gradations
  FOR EACH ROW EXECUTE FUNCTION verifier_gradation_meme_fiche();
