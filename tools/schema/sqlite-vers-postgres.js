#!/usr/bin/env node
// ================================================================================================
// OUTIL PONCTUEL — génère la migration Postgres initiale à partir du schéma SQLite FINAL de la
// version Electron 1.0.1 (celui qu'obtient une base après toutes ses migrations).
//
//   node tools/schema/sqlite-vers-postgres.js <base.sqlite> > apps/api/migrations/001_schema_initial.sql
//
// Une fois la migration 001 générée et relue, c'est ELLE qui fait foi ; cet outil n'est conservé
// que pour la traçabilité de la conversion.
// ================================================================================================
const path = require("path");
const Database = require(process.env.BETTER_SQLITE3 || "better-sqlite3");

const fichier = process.argv[2];
if (!fichier) { console.error("Usage : sqlite-vers-postgres.js <base.sqlite>"); process.exit(1); }
const db = new Database(fichier, { readonly: true });

const tables = db.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
const index = db.prepare("SELECT name, tbl_name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name").all();
const triggers = db.prepare("SELECT name, tbl_name, sql FROM sqlite_master WHERE type='trigger' ORDER BY name").all();

function convertirDefinition(sql) {
  let s = sql;
  s = s.replace(/\bINTEGER\s+PRIMARY\s+KEY(\s+AUTOINCREMENT)?/gi, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
  s = s.replace(/DEFAULT\s*\(\s*datetime\('now'\)\s*\)/gi, "DEFAULT (maintenant())");
  s = s.replace(/DEFAULT\s*\(\s*date\('now'\)\s*\)/gi, "DEFAULT (aujourdhui())");
  s = s.replace(/datetime\('now'\)/gi, "maintenant()");
  s = s.replace(/date\('now'\)/gi, "aujourdhui()");
  // Types : on garde TEXT pour les dates (format SQLite 'AAAA-MM-JJ HH:MM:SS' conservé à l'identique).
  s = s.replace(/(\b[a-z_][a-z0-9_]*\s+)INTEGER\b/gi, "$1BIGINT");
  s = s.replace(/(\b[a-z_][a-z0-9_]*\s+)REAL\b/gi, "$1DOUBLE PRECISION");
  s = s.replace(/(\b[a-z_][a-z0-9_]*\s+)(datetime|date)\b(?!\s*\()/gi, "$1TEXT");
  s = s.replace(/(\b[a-z_][a-z0-9_]*\s+)BLOB\b/gi, "$1BYTEA");
  s = s.replace(/\bCREATE TABLE\s+IF NOT EXISTS\s+/i, "CREATE TABLE ");
  s = s.replace(/\bCREATE TABLE\s+"?([A-Za-z0-9_]+)"?/i, "CREATE TABLE $1");
  return s;
}

// Ordre de création : une table après celles qu'elle référence.
const deps = new Map();
for (const t of tables) {
  const refs = new Set();
  for (const m of t.sql.matchAll(/REFERENCES\s+"?([A-Za-z0-9_]+)"?/gi)) if (m[1] !== t.name) refs.add(m[1]);
  deps.set(t.name, refs);
}
const ordre = []; const vu = new Set(); const enCours = new Set();
function visiter(nom) {
  if (vu.has(nom)) return;
  if (enCours.has(nom)) throw new Error("Dépendance circulaire sur " + nom);
  enCours.add(nom);
  for (const d of deps.get(nom) || []) if (deps.has(d)) visiter(d);
  enCours.delete(nom); vu.add(nom); ordre.push(nom);
}
tables.forEach((t) => visiter(t.name));
const parNom = new Map(tables.map((t) => [t.name, t]));

const out = [];
out.push("-- ================================================================================================");
out.push("-- 001 — Schéma initial PostgreSQL, converti du schéma SQLite final de Belvie ERP 1.0.1.");
out.push("-- Généré par tools/schema/sqlite-vers-postgres.js puis relu. Ce fichier fait foi.");
out.push("--");
out.push("-- Choix de conversion (phase 1 : iso-fonctionnel) :");
out.push("--   * INTEGER → BIGINT ; clés primaires → IDENTITY (BY DEFAULT, pour la reprise des données) ;");
out.push("--   * REAL → DOUBLE PRECISION ;");
out.push("--   * dates conservées en TEXT au format SQLite ('AAAA-MM-JJ' / 'AAAA-MM-JJ HH:MM:SS', UTC) ;");
out.push("--   * datetime('now') / date('now') → maintenant() / aujourdhui() (définies ci-dessous) ;");
out.push("--   * triggers updated_at réécrits en PL/pgSQL.");
out.push("-- ================================================================================================");
out.push("");
out.push("CREATE OR REPLACE FUNCTION maintenant() RETURNS TEXT LANGUAGE sql STABLE AS");
out.push("  $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;");
out.push("CREATE OR REPLACE FUNCTION aujourdhui() RETURNS TEXT LANGUAGE sql STABLE AS");
out.push("  $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD') $$;");
out.push("");
for (const nom of ordre) {
  out.push(convertirDefinition(parNom.get(nom).sql).trim() + ";");
  out.push("");
}
out.push("-- Index");
for (const i of index) out.push(convertirDefinition(i.sql).replace(/CREATE (UNIQUE )?INDEX IF NOT EXISTS/i, "CREATE $1INDEX").trim() + ";");
out.push("");
out.push("-- Triggers");
out.push("CREATE OR REPLACE FUNCTION maj_updated_at() RETURNS trigger LANGUAGE plpgsql AS");
out.push("  $$ BEGIN NEW.updated_at := maintenant(); RETURN NEW; END $$;");
for (const t of triggers) {
  const m = /^trg_(.+)_updated_at$/.exec(t.name);
  if (m) {
    out.push(`CREATE TRIGGER ${t.name} BEFORE UPDATE ON ${t.tbl_name} FOR EACH ROW EXECUTE FUNCTION maj_updated_at();`);
  } else {
    out.push(`-- À CONVERTIR À LA MAIN : ${t.name}`);
    out.push("/* " + t.sql + " */");
  }
}
process.stdout.write(out.join("\n") + "\n");
